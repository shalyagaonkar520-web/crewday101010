#!/usr/bin/env node
/**
 * Builds src/seo/content.generated.ts from the Markdown in content/seo/:
 *
 *   content/seo/guides/*.md   one file per guide, served at /guides/<slug>
 *   content/seo/faq.md        the FAQ page, served at /faq
 *
 *   npm run seo:content            write the file
 *   npm run seo:content -- --check fail if the file is out of date (CI)
 *
 * The format is in content/seo/README.md. Any broken rule (title over 60
 * characters, no direct answer, no FAQs...) stops the build with the file name,
 * so a bad page never reaches the site.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { parseContent } from './lib/seoMarkdown.mjs'

const ROOT = 'content/seo'
const OUT = 'src/seo/content.generated.ts'
const check = process.argv.includes('--check')

const errors = []
const warnings = []
const read = (file, kind) => {
  const result = parseContent(readFileSync(file, 'utf8'), { fileName: path.relative('.', file), kind })
  errors.push(...result.errors)
  warnings.push(...result.warnings)
  return result.content
}

const guideDir = path.join(ROOT, 'guides')
const guideFiles = existsSync(guideDir)
  ? readdirSync(guideDir)
      .filter((name) => name.toLowerCase().endsWith('.md'))
      .sort()
  : []
const guides = guideFiles.map((name) => read(path.join(guideDir, name), 'guide'))
const faqFile = path.join(ROOT, 'faq.md')
const faq = existsSync(faqFile) ? read(faqFile, 'faq') : null

const seen = new Set()
for (const guide of guides) {
  if (seen.has(guide.slug)) errors.push(`two guides use the slug "${guide.slug}"`)
  seen.add(guide.slug)
}

for (const warning of warnings) console.warn(`warning: ${warning}`)
if (errors.length) {
  console.error(`SEO content has ${errors.length} problem(s):\n  ${errors.join('\n  ')}`)
  process.exit(1)
}

const output = `// Generated by \`npm run seo:content\` from content/seo/. Do not edit by hand.
import type { GuideContent } from './guides.js'

export const GUIDE_CONTENT: GuideContent[] = ${JSON.stringify(guides, null, 2)}

export const FAQ_PAGE_CONTENT: GuideContent | null = ${JSON.stringify(faq, null, 2)}
`

const current = existsSync(OUT) ? readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : ''
if (check) {
  if (current !== output) {
    console.error(`${OUT} is out of date. Run: npm run seo:content`)
    process.exit(1)
  }
  console.log(`${OUT} is up to date (${guides.length} guide(s), FAQ page: ${faq ? 'yes' : 'no'}).`)
} else {
  writeFileSync(OUT, output)
  const questions = guides.reduce((sum, guide) => sum + guide.faqs.flatMap((g) => g.items).length, 0)
  const faqQuestions = faq ? faq.faqs.flatMap((g) => g.items).length : 0
  console.log(
    `Wrote ${OUT}: ${guides.length} guide(s) with ${questions} FAQ(s), FAQ page ${faq ? `with ${faqQuestions} question(s)` : 'not present'}.`,
  )
}
